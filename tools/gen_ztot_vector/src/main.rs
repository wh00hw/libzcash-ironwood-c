//! Generates tests/test_ztot_vector.h: a real v6 shielded -> transparent
//! transaction (one Ironwood spend, one transparent P2PKH output, Ironwood
//! change; the builder pads the bundle to two actions with a dummy spend and
//! a DUMMY OUTPUT — zero value, random address, 512 zero bytes of memo, no
//! OVK) built with zcash_primitives' Builder,
//! with the shielded signature hash computed by the pczt Signer role.
//!
//! tests/test_ironwood.c replays it through the device's signer and requires
//! the device's sighash to equal the crate's: the check that the transparent
//! leaf for "no transparent inputs, some transparent outputs" is right, and
//! that every output the `orchard` builder emits — dummies included — passes
//! the device's mandatory ciphertext check.
use incrementalmerkletree::{Hashable, Level};
use orchard::keys::{FullViewingKey, Scope, SpendingKey};
use orchard::note::{ExtractedNoteCommitment, NoteVersion, RandomSeed, Rho};
use orchard::tree::{MerkleHashOrchard, MerklePath};
use pczt::roles::{creator::Creator, io_finalizer::IoFinalizer};
use zcash_primitives::transaction::{
    builder::{BuildConfig, Builder, BundlePadding, PcztResult},
    fees::zip317,
};
use zcash_protocol::consensus::{BlockHeight, MAIN_NETWORK};
use zcash_protocol::memo::MemoBytes;
use zcash_protocol::value::Zatoshis;
use zcash_transparent::address::TransparentAddress;

#[derive(Debug)]
struct E;
impl From<pczt::roles::low_level_signer::OrchardParseError> for E {
    fn from(_: pczt::roles::low_level_signer::OrchardParseError) -> Self {
        E
    }
}

fn arr(name: &str, b: &[u8]) {
    print!("static const uint8_t {}[{}] = {{", name, b.len());
    for (i, x) in b.iter().enumerate() {
        if i % 16 == 0 {
            print!("\n    ");
        }
        print!("0x{:02x},", x);
    }
    println!("\n}};");
}

fn main() {
    let mut rng = rand_core::UnwrapErr(rand::rngs::SysRng);
    let sk = SpendingKey::from_bytes([7u8; 32]).unwrap();
    let fvk = FullViewingKey::from(&sk);
    let external = fvk.address_at(0u32, Scope::External);
    let internal = fvk.address_at(0u32, Scope::Internal);

    const SPENT: u64 = 1_000_000_000;
    const T_OUT: u64 = 400_000_000;
    let mut n = 0u8;
    let note: orchard::Note = loop {
        n += 1;
        let Some(rho) = Option::<Rho>::from(Rho::from_bytes(&[n; 32])) else { continue };
        let Some(rseed) = Option::<RandomSeed>::from(RandomSeed::from_bytes([n; 32], &rho)) else {
            continue;
        };
        if let Some(note) = Option::<orchard::Note>::from(orchard::Note::from_parts(
            external,
            orchard::value::NoteValue::from_raw(SPENT),
            rho,
            rseed,
            NoteVersion::V3,
        )) {
            break note;
        }
    };
    let cmx: ExtractedNoteCommitment = note.commitment().into();
    let mut auth_path = [MerkleHashOrchard::empty_leaf(); 32];
    for (level, sibling) in auth_path.iter_mut().enumerate() {
        *sibling = MerkleHashOrchard::empty_root(Level::from(level as u8));
    }
    let merkle_path = MerklePath::from_parts(0, auth_path);

    // ZIP 317 fee: 5000 per logical action; try the plausible counts.
    for fee in [15_000u64, 20_000, 10_000] {
        let mut builder = Builder::new(
            MAIN_NETWORK,
            BlockHeight::from_u32(3_600_000),
            BuildConfig::Standard {
                sapling_anchor: None,
                orchard_anchor: None,
                ironwood_anchor: Some(merkle_path.root(cmx)),
                orchard_padding: BundlePadding::DEFAULT,
                ironwood_padding: BundlePadding::DEFAULT,
            },
        );
        builder
            .add_ironwood_spend::<zip317::FeeRule>(fvk.clone(), note, merkle_path.clone())
            .unwrap();
        builder
            .add_transparent_output(
                &TransparentAddress::PublicKeyHash([0xB2; 20]),
                Zatoshis::const_from_u64(T_OUT),
            )
            .unwrap();
        let change = SPENT - T_OUT - fee;
        builder
            .add_ironwood_output::<zip317::FeeRule>(
                Some(fvk.to_ovk(Scope::Internal)),
                internal,
                Zatoshis::const_from_u64(change),
                MemoBytes::empty(),
            )
            .unwrap();
        let Ok(PcztResult { pczt_parts, .. }) =
            builder.build_for_pczt(&mut rng, &zip317::FeeRule::standard())
        else {
            continue;
        };
        let pczt = IoFinalizer::new(Creator::build_from_parts(pczt_parts).unwrap())
            .finalize_io(&mut rng)
            .unwrap();

        let signer = pczt::roles::signer::Signer::new(pczt.clone()).expect("signer");
        let sighash = signer.shielded_sighash();
        let tx = pczt.clone().into_effects().expect("effects");

        println!("/* Generated by tools/gen_ztot_vector (zcash_primitives 0.31.0, pczt 0.10.0,");
        println!(" * orchard 0.16.0). Do not edit. A real v6 shielded -> transparent");
        println!(" * transaction and its shielded signature hash as computed by the crates. */");
        println!("#pragma once\n#include <stdint.h>\n");
        let b = fvk.to_bytes();
        arr("ZTOT_AK", &b[..32]);
        arr("ZTOT_NK", &b[32..64]);
        arr("ZTOT_RIVK", &b[64..]);
        println!("#define ZTOT_COIN_TYPE 133u");
        println!("#define ZTOT_VERSION 0x{:08x}u", tx.version().header());
        println!("#define ZTOT_VERSION_GROUP_ID 0x{:08x}u", tx.version().version_group_id());
        println!("#define ZTOT_BRANCH_ID 0x{:08x}u", u32::from(tx.consensus_branch_id()));
        println!("#define ZTOT_LOCK_TIME {}u", tx.lock_time());
        println!("#define ZTOT_EXPIRY_HEIGHT {}u", u32::from(tx.expiry_height()));
        let iw = pczt.ironwood();
        let (mag, neg) = *iw.value_sum();
        println!("#define ZTOT_IRONWOOD_FLAGS 0x{:02x}", *iw.flags());
        println!("#define ZTOT_IRONWOOD_VALUE_BALANCE ((int64_t){}{}LL)", if neg { "-" } else { "" }, mag);
        println!("#define ZTOT_ORCHARD_FLAGS 0x{:02x} /* what the PCZT carries for the absent Orchard bundle */", *pczt.orchard().flags());
        println!("#define ZTOT_ORCHARD_ACTIONS {}", pczt.orchard().actions().len());
        println!("#define ZTOT_FEE {}ull", fee);
        println!("#define ZTOT_T_OUT_VALUE {}ull", T_OUT);
        println!("#define ZTOT_CHANGE_VALUE {}ull", change);
        let touts = pczt.transparent().outputs();
        assert_eq!(touts.len(), 1);
        assert_eq!(pczt.transparent().inputs().len(), 0);
        arr("ZTOT_T_OUT_SCRIPT", touts[0].script_pubkey());
        arr("ZTOT_CHANGE_ADDR", &internal.to_raw_address_bytes());

        let pa = iw.actions().clone();
        println!("#define ZTOT_N_ACTIONS {}", pa.len());
        let low = pczt::roles::low_level_signer::Signer::new(pczt.clone());
        let mut rows: Vec<Vec<u8>> = Vec::new();
        low.sign_ironwood_with(|_p, bundle, _m| -> Result<(), E> {
                for (i, action) in bundle.actions().iter().enumerate() {
                    let enc = action.output().encrypted_note();
                    let mut a = Vec::new();
                    a.extend_from_slice(&action.cv_net().to_bytes());
                    a.extend_from_slice(&action.spend().nullifier().to_bytes());
                    a.extend_from_slice(&<[u8; 32]>::from(action.spend().rk().clone()));
                    a.extend_from_slice(&action.output().cmx().to_bytes());
                    a.extend_from_slice(&enc.epk_bytes);
                    a.extend_from_slice(&enc.enc_ciphertext.0);
                    a.extend_from_slice(&enc.out_ciphertext);
                    assert_eq!(a.len(), 820);
                    let o = pa[i].output();
                    a.extend_from_slice(&o.recipient().expect("recipient"));
                    a.extend_from_slice(&o.value().expect("value").to_le_bytes());
                    a.extend_from_slice(&o.rseed().expect("rseed"));
                    rows.push(a);
                }
                Ok(())
            })
            .expect("ironwood bundle");
        assert_eq!(rows.len(), pa.len());
        println!("/* per action: action[820] || recipient[43] || value[8 LE] || rseed[32] */");
        println!("static const uint8_t ZTOT_ACTIONS[ZTOT_N_ACTIONS][903] = {{");
        for r in &rows {
            print!("  {{");
            for (i, x) in r.iter().enumerate() {
                if i % 24 == 0 {
                    print!("\n    ");
                }
                print!("0x{:02x},", x);
            }
            println!("\n  }},");
        }
        println!("}};");
        arr("ZTOT_SIGHASH", &sighash);
        return;
    }
    panic!("no fee value balanced the transaction");
}
