#!/usr/bin/env python3
"""Regenerate src/pallas_sqrt_table.h (tables for fp_sqrt in src/pallas.c).

    python3 tools/gen_sqrt_table.py > src/pallas_sqrt_table.h
"""
p = 0x40000000000000000000000000000000224698FC094CF91B992D30ED00000001
T = (p - 1) >> 32
assert (p - 1) == T << 32 and T & 1
g = pow(5, T, p)                      # generator of the order-2^32 subgroup
assert pow(g, 1 << 31, p) == p - 1
ginv = pow(g, -1, p)
R = pow(g * g % p, 1 << 27, p)        # primitive 16th root of unity
assert pow(R, 16, p) == 1 and pow(R, 8, p) != 1


def fmt(x):
    limbs = [(x >> (29 * i)) & ((1 << 29) - 1) for i in range(9)]
    return "{{" + ",".join("0x%08x" % v for v in limbs) + "}}"


print("""// Tables for the Pallas base-field square root (src/pallas.c: fp_sqrt).
//
// p - 1 = 2^32 * T with T odd; g = 5^T generates the 2-Sylow subgroup
// (order 2^32). For a square a, t = a^T lies in the order-2^31 subgroup
// generated by g^2, and fp_sqrt recovers e' with t = (g^2)^e' four bits at
// a time (Pohlig-Hellman), then returns a^((T+1)/2) * g^(-e').
//
//   FP_SQRT_GINV[j][i] = g^(-i * 16^j)          (j = 0..7, i = 0..15)
//   FP_SQRT_ROOT[i]    = (g^2)^(i * 2^27)       (the 16th roots of unity)
//
// Generated by tools/gen_sqrt_table.py; values are base-2^29 limbs.
#pragma once
#include "bignum.h"

/* (T - 1) / 2 */
static const bignum256 FP_SQRT_EXP = %s;

static const bignum256 FP_SQRT_ROOT[16] = {""" % fmt((T - 1) // 2))
for i in range(16):
    print("    %s," % fmt(pow(R, i, p)))
print("};\n\nstatic const bignum256 FP_SQRT_GINV[8][16] = {")
for j in range(8):
    print("    {")
    for i in range(16):
        print("        %s," % fmt(pow(ginv, i * 16**j, p)))
    print("    },")
print("};")
