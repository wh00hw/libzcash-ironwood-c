#!/usr/bin/env python3
"""Regenerate src/pallas_fixed_base_table.h (comb tables for
pallas_point_mul_fixed in src/pallas.c).

    python3 tools/gen_fixed_base_table.py [BLOCKS] > src/pallas_fixed_base_table.h

BLOCKS (default 2) is the number of sub-tables per base: each one costs
15 affine points (1080 B) of flash and halves the doublings of a
multiplication (64 / BLOCKS).

The base points are read from src/pallas_consts.h, so the tables cannot
drift from the constants the rest of the library uses. Independent of the C
code: plain Python integers, affine arithmetic. pallas_verify_fixed_points()
rebuilds every entry with the library's own arithmetic and compares.
"""
import os
import re
import sys

p = 0x40000000000000000000000000000000224698FC094CF91B992D30ED00000001
TEETH = 4
BLOCKS = int(sys.argv[1]) if len(sys.argv) > 1 else 2
assert 256 % (TEETH * BLOCKS) == 0
SPACING = 256 // (TEETH * BLOCKS)

# (enum name, hash-to-curve domain, message) — order defines pallas_fixed_base.
BASES = [
    ("PALLAS_BASE_SPEND_AUTH_G", "z.cash:Orchard", "G"),
    ("PALLAS_BASE_NOTE_COMMIT_R", "z.cash:Orchard-NoteCommit-r", ""),
    ("PALLAS_BASE_COMMIT_IVK_R", "z.cash:Orchard-CommitIvk-r", ""),
]


def add(P, Q):
    """Affine addition on y^2 = x^3 + 5; None is the identity."""
    if P is None:
        return Q
    if Q is None:
        return P
    (x1, y1), (x2, y2) = P, Q
    if x1 == x2:
        if (y1 + y2) % p == 0:
            return None
        lam = 3 * x1 * x1 * pow(2 * y1, -1, p) % p
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (lam * lam - x1 - x2) % p
    return (x3, (lam * (x1 - x3) - y1) % p)


def load_bases():
    here = os.path.dirname(os.path.abspath(__file__))
    src = open(os.path.join(here, "..", "src", "pallas_consts.h")).read()
    found = {}
    for dom, msg, body in re.findall(r'\{"([^"]*)",\s*"([^"]*)",\s*\{([^}]*)\}\}', src):
        xy = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body))
        assert len(xy) == 64
        x = int.from_bytes(xy[:32], "little")
        y = int.from_bytes(xy[32:], "little")
        assert x < p and y < p and (y * y - x * x * x - 5) % p == 0
        found[(dom, msg)] = (x, y)
    return [found[(dom, msg)] for _, dom, msg in BASES]


def fmt(v):
    limbs = [(v >> (29 * i)) & ((1 << 29) - 1) for i in range(9)]
    return "{{" + ",".join("0x%08x" % l for l in limbs) + "}}"


print("""// Comb tables for constant-time fixed-base scalar multiplication
// (src/pallas.c: pallas_point_mul_fixed).
//
// A 256-bit scalar is cut into PALLAS_COMB_TEETH * PALLAS_COMB_BLOCKS
// consecutive pieces of PALLAS_COMB_SPACING bits; piece m = t*BLOCKS + u
// belongs to tooth t of block u. For a base B:
//
//   PALLAS_COMB_TABLE[base][u][d - 1] = sum over the set bits t of d of
//                                       [2^((t*BLOCKS + u) * SPACING)] B
//
// for d = 1..15, affine. Digit 0 (the identity) has no entry.
//
// Bases, in pallas_fixed_base order (points from src/pallas_consts.h):""")
for name, dom, msg in BASES:
    print('//   %-26s hash_to_curve("%s")("%s")' % (name, dom, msg))
print("""//
// Generated by tools/gen_fixed_base_table.py %d; values are base-2^29 limbs.
// pallas_verify_fixed_points() recomputes every entry.
#pragma once
#include "bignum.h"

#define PALLAS_COMB_TEETH %d
#define PALLAS_COMB_BLOCKS %d
#define PALLAS_COMB_SPACING %d
#define PALLAS_COMB_ENTRIES ((1u << PALLAS_COMB_TEETH) - 1u)
#define PALLAS_COMB_BASES %d

typedef struct {
    bignum256 x, y;
} pallas_comb_point;

static const pallas_comb_point
    PALLAS_COMB_TABLE[PALLAS_COMB_BASES][PALLAS_COMB_BLOCKS][(1u << PALLAS_COMB_TEETH) - 1u] = {"""
      % (BLOCKS, TEETH, BLOCKS, SPACING, len(BASES)))

for (name, dom, msg), B in zip(BASES, load_bases()):
    # pieces[m] = [2^(m*SPACING)] B
    pieces = []
    P = B
    for m in range(TEETH * BLOCKS):
        pieces.append(P)
        for _ in range(SPACING):
            P = add(P, P)
    print("    { /* %s */" % name)
    for u in range(BLOCKS):
        print("        {")
        for d in range(1, 1 << TEETH):
            acc = None
            for t in range(TEETH):
                if (d >> t) & 1:
                    acc = add(acc, pieces[t * BLOCKS + u])
            assert acc is not None
            print("            {%s,\n             %s}," % (fmt(acc[0]), fmt(acc[1])))
        print("        },")
    print("    },")
print("};")
